const GEMINI_API_KEY = "YOUR_GEMINI_API_KEY_HERE";
const GEMINI_MODEL_ID = "gemini-pro";

const makeGeminiRequest = async (promptContent) => {
  try {
    const response = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/" + GEMINI_MODEL_ID + ":generateContent?key=" + GEMINI_API_KEY,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          contents: [{ parts: [{ text: promptContent }] }],
        }),
      }
    );

    if (!response.ok) {
      const errorBody = await response.json();
      throw new Error("Gemini API error " + response.status + " " + JSON.stringify(errorBody));
    }

    const data = await response.json();
    const generatedText = data.candidates && data.candidates[0] && data.candidates[0].content && data.candidates[0].content.parts && data.candidates[0].content.parts[0] && data.candidates[0].content.parts[0].text;

    if (!generatedText) {
      throw new Error("No text generated by Gemini.");
    }

    return generatedText;
  } catch (error) {
    throw error;
  }
};

const updateSheet = async (sheet) => {
  if (!(sheet.rejectedRecords && sheet.rejectedRecords.length)) {
    return;
  }

  const rejectedRecordsIds = sheet.rejectedRecords.map((record) => record.id);
  const sheetRecordsResponse = await api.records.get(sheet.sheetId);

  const rejectedSheetRecords =
    sheetRecordsResponse.data.records && sheetRecordsResponse.data.records.filter((record) =>
      rejectedRecordsIds.includes(record.id),
    );

  (rejectedSheetRecords || []).forEach((sheetRecord) => {
    const record = sheetRecord;
    const rejectedRecord =
      sheet.rejectedRecords.find((item) => item.id === record.id) || undefined;
    if (rejectedRecord) {
      rejectedRecord.values.forEach((value) => {
        if (record.values[value.field]) {
          record.values[value.field].messages = [
            {
              type: "error",
              message: value.message,
            },
          ];
        }
      });
    }
  });
  await api.records.update(sheet.sheetId, { records: rejectedSheetRecords });
};

const getSheetId = async (workbookId) => {
  const { data: workbookSheets } = await api.sheets.list({ workbookId });
  return workbookSheets[0] && workbookSheets[0].id;
};

const getSheetRecords = async (
  workbookSheetId,
  jobId,
  resource,
) => {
  const { data: sheetRecords } = await api.records.get(workbookSheetId);

  const records = sheetRecords && sheetRecords.records;

  if (!records) {
    await api.jobs.fail(jobId, {
      outcome: {
        message: "Upload is empty.",
      },
    });
    return [];
  }

  if (resource !== "invoices" && records.length > 1000) {
    await api.jobs.fail(jobId, {
      outcome: {
        message: "Too many rows max is 1000, " + records.length + " submitted.",
      },
    });
    return [];
  }
  return sheetRecords && sheetRecords.records;
};

const geminiSanitizeAndFlattenData = async (flatfileRecords, fieldKeySet) => {
  const prompt = "You are an expert data transformation engine. I will provide a JSON array of raw Flatfile records. Your task is to flatten the nested Flatfile data structure into a simple key-value pair for each record and sanitize any metadata fields that are not part of the core data. Only include fields specified in the provided 'fieldKeySet'. Ensure all values are in their most appropriate type e.g. numbers are numbers, booleans are booleans, dates are ISO strings. Return the transformed data as a JSON array of objects.\n\n" +
    "Field Keys to Keep:\n" +
    JSON.stringify(Array.from(fieldKeySet)) + "\n\n" +
    "Raw Flatfile Records:\n" +
    JSON.stringify(flatfileRecords);

  const geminiResponse = await makeGeminiRequest(prompt);
  try {
    const sanitizedData = JSON.parse(geminiResponse);
    if (!Array.isArray(sanitizedData)) {
      throw new Error("Gemini did not return an array for sanitized data.");
    }
    return sanitizedData;
  } catch (parseError) {
    throw new Error("Failed to parse Gemini sanitization response: " + parseError.message + " Raw response: " + geminiResponse);
  }
};

const geminiValidateData = async (sanitizedRecordData, sheetSchema) => {
  const prompt = "You are an expert data validator. I will provide a JSON array of data records and a JSON object representing the expected schema for each record. Your task is to validate each record against the schema and identify any errors. For each error, provide the record ID, the field name, and a concise error message. Return your response as a JSON array of validation rejections, where each rejection object has 'id', 'field', and 'message' properties. If there are no errors, return an empty JSON array.\n\n" +
    "Schema:\n" +
    JSON.stringify(sheetSchema) + "\n\n" +
    "Data:\n" +
    JSON.stringify(sanitizedRecordData);

  const geminiResponse = await makeGeminiRequest(prompt);
  try {
    const rejections = JSON.parse(geminiResponse);
    if (!Array.isArray(rejections)) {
      throw new Error("Gemini did not return an array for validation rejections.");
    }
    return rejections;
  } catch (parseError) {
    throw new Error("Failed to parse Gemini validation response: " + parseError.message + " Raw response: " + geminiResponse);
  }
};

const geminiAnalyzeSubmission = async (sanitizedRecordData, resource) => {
  const prompt = "You are an expert data analyst for a bulk import system. I have a JSON array of sanitized and validated data records for a '" + resource + "' resource, ready for submission. Your task is to perform a final check and suggest any additional categorization or processing flags that might be useful during submission. If everything looks good for direct submission, indicate that. If there are specific categories or tags that should be applied based on the data content, suggest them. Return a JSON object with a 'readyForSubmission' boolean and an optional 'submissionMetadata' object containing any suggested flags or categories.\n\n" +
    "Resource Type: " + resource + "\n\n" +
    "Sanitized Data:\n" +
    JSON.stringify(sanitizedRecordData);

  const geminiResponse = await makeGeminiRequest(prompt);
  try {
    const analysis = JSON.parse(geminiResponse);
    if (typeof analysis.readyForSubmission !== "boolean") {
      throw new Error("Gemini analysis did not include a 'readyForSubmission' boolean.");
    }
    return analysis;
  } catch (parseError) {
    throw new Error("Failed to parse Gemini submission analysis response: " + parseError.message + " Raw response: " + geminiResponse);
  }
};

const tryValidate = async (
  sanitizedRecordData,
  jobId,
  sheetId,
  sheetSchema
) => {
  try {
    const rejectedRecords = await geminiValidateData(sanitizedRecordData, sheetSchema);

    if (rejectedRecords.length > 0) {
      await updateSheet({
        rejectedRecords: rejectedRecords,
        sheetId: sheetId,
      });

      await api.jobs.fail(jobId, {
        outcome: {
          message: "Submission failed. Please correct all errors before submitting again.",
        },
      });

      return false;
    }
    return true;
  } catch (err) {
    await api.jobs.fail(jobId, {
      outcome: {
        message: "Bulk import validation failed due to Gemini error " + err.message + ".",
      },
    });

    return false;
  }
};

const trySubmit = async (
  sanitizedRecordData,
  workbookSheetId,
  jobId,
  spaceId,
  resource,
  onSubmit
) => {
  try {
    const geminiSubmissionAnalysis = await geminiAnalyzeSubmission(sanitizedRecordData, resource);

    if (!geminiSubmissionAnalysis.readyForSubmission) {
      await api.jobs.fail(jobId, {
        outcome: {
          message: "Gemini determined data is not yet ready for submission: " + JSON.stringify(geminiSubmissionAnalysis.submissionMetadata || {}) + ".",
        },
      });
      return;
    }

    const response = await onSubmit(
      sanitizedRecordData,
      workbookSheetId,
      spaceId,
      geminiSubmissionAnalysis.submissionMetadata || {}
    );
    if (response.success) {
      let path = "";
      if (response.path) {
        path = response.path;
      } else if (response.bulkImportId) {
        path = "/bulk_imports/" + response.bulkImportId;
      } else {
        path = "/" + resource;
      }

      await api.jobs.complete(jobId, {
        outcome: {
          heading: "Bulk Import Submitted",
          message:
            "Thank you, we are processing your file and will send you an email upon completion.",
          acknowledge: true,
          next: {
            type: "url",
            url: window.location.origin + path,
            label: "View Bulk Import",
          },
        },
      });
    } else {
       await api.jobs.fail(jobId, {
        outcome: {
          message: "Bulk import creation failed by onSubmit: " + (response.message || "Unknown error") + ".",
        },
      });
    }
  } catch (err) {
    await api.jobs.fail(jobId, {
      outcome: {
        message: "Bulk import creation failed due to Gemini or onSubmit error: " + err.message + ".",
      },
    });
  }
};

const getFlatfileListener = (
  resource,
  fieldKeySet,
  sheetSchema,
  onSubmit
) =>
  FlatfileListener.create((listener) => {
    listener.on(
      "job:ready",
      { job: "workbook:submitActionFg" },
      async ({ context: { jobId, workbookId, spaceId } }) => {
        const sheetId = await getSheetId(workbookId);
        const sheetRecords = await getSheetRecords(
          sheetId,
          jobId,
          resource,
        );

        if (sheetRecords && sheetRecords.length) {
          const sanitizedRecordData = await geminiSanitizeAndFlattenData(
            sheetRecords,
            fieldKeySet,
          );

          const valid = await tryValidate(
            sanitizedRecordData,
            jobId,
            sheetId,
            sheetSchema,
          );

          if (valid) {
            await trySubmit(
              sanitizedRecordData,
              sheetId,
              jobId,
              spaceId,
              resource,
              onSubmit,
            );
          }
        }
      },
    );
  });

export default getFlatfileListener;