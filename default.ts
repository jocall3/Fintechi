/**
 * @interface DashboardItem
 * Represents a single widget or component within the dashboard.
 * Expanded to include AI-specific configuration and metadata.
 */
export interface DashboardItem {
  id: string;
  width: "full" | "half" | "quarter" | "third" | "two-thirds"; // Expanded width options
  componentType?: string; // e.g., 'SalesChart', 'UserActivityFeed', 'KeyMetrics', 'RecommendationEngine'
  dataQuery?: string; // AI-generated query or identifier for data source
  aiConfig?: {
    prompt?: string;
    model?: string;
    version?: string;
    relevanceScore?: number;
    generatedAt?: string;
  };
  layoutPriority?: number; // AI-determined priority for placement
  contextualTags?: string[]; // Tags generated by AI for context
  dependencies?: string[]; // Other items this item depends on
}

/**
 * @interface AdaptiveDashboardProps
 * Extends the base DashboardProps with AI-specific metadata about its generation.
 * This represents a living, evolving dashboard structure.
 */
export interface AdaptiveDashboardProps extends DashboardProps {
  items: DashboardItem[]; // Ensure items conform to our expanded interface
  generationMetadata?: {
    aiModelUsed: string;
    timestamp: string;
    userContextHash: string; // Hashed user context for privacy and lookup
    optimizationScore: number; // AI's self-assessment of the dashboard's relevance
    fallbackUsed: boolean; // Indicates if a fallback template was used
    generationTimeMs: number;
    promptUsed: string;
  };
}

