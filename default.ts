export class MockComplianceEngine implements IComplianceEngine {
  async auditDashboard(dashboard: AdaptiveDashboardProps, userContext: any): Promise<{ compliant: boolean; issues: string[] }> {
    const issues: string[] = [];
    let compliant = true;

    // Rule 1: No more than 5 items for 'standard' tier users unless explicit permission
    if (userContext.tier === 'standard' && dashboard.items.length > 5 && !(await authenticationService.hasPermission('OVERRIDE_ITEM_LIMIT'))) {
      issues.push(`Standard tier users are limited to 5 dashboard items. Current: ${dashboard.items.length}.`);
      compliant = false;
    }

    // Rule 2: Ensure data queries are safe (very simplified for demo, production would use a proper parser/linter)
    for (const item of dashboard.items) {
      if (item.dataQuery && (item.dataQuery.toLowerCase().includes('delete') || item.dataQuery.toLowerCase().includes('drop'))) {
        issues.push(`Potentially unsafe data modification query detected in item ${item.id}: ${item.dataQuery}.`);
        compliant = false;
      }
    }

    // Rule 3: Check for data residency compliance (conceptual)
    if (userContext.department === 'EU_Customer') {
      for (const item of dashboard.items) {
        if (item.dataQuery?.includes('US_REGION_DB')) { // Assuming US_REGION_DB is a specific identifier
          issues.push(`EU customer dashboard item '${item.id}' queries data from non-EU region (US_REGION_DB).`);
          compliant = false;
        }
      }
    }

    // Rule 4: Ensure all required items for a department are present (conceptual)
    if (userContext.department === 'Sales' && !dashboard.items.some(item => item.componentType === 'SalesChart')) {
      issues.push(`Sales department dashboard missing mandatory 'SalesChart' component.`);
      compliant = false;
    }

    telemetryService.logEvent("ComplianceAudit", { userId: userContext.userId, compliant, issues });
    return { compliant, issues };
  }

  async enforcePolicy(dashboard: AdaptiveDashboardProps, userContext: any): Promise<AdaptiveDashboardProps> {
    const { compliant, issues } = await this.auditDashboard(dashboard, userContext);
    if (!compliant) {
      telemetryService.logEvent("ComplianceEnforcementInitiated", { userId: userContext.userId, issues });
      let enforcedDashboard = { ...dashboard };

      // Example enforcement: Trim excess items for standard tier
      if (userContext.tier === 'standard' && enforcedDashboard.items.length > 5) {
        enforcedDashboard.items = enforcedDashboard.items.slice(0, 5);
        issues.push("Enforced: Trimmed dashboard items for standard tier.");
      }

      // Example enforcement: Remove unsafe queries
      enforcedDashboard.items = enforcedDashboard.items.map(item => {
        if (item.dataQuery && (item.dataQuery.toLowerCase().includes('delete') || item.dataQuery.toLowerCase().includes('drop'))) {
          issues.push(`Enforced: Removed unsafe data query from item '${item.id}'.`);
          return { ...item, dataQuery: 'BLOCKED_UNSAFE_QUERY' }; // Replace with a safe placeholder
        }
        return item;
      });

      // Example enforcement: Replace non-compliant data sources for EU users
      if (userContext.department === 'EU_Customer') {
        enforcedDashboard.items = enforcedDashboard.items.map(item => {
          if (item.dataQuery?.includes('US_REGION_DB')) {
            issues.push(`Enforced: Rerouted data query for item '${item.id}' to EU-compliant source.`);
            return { ...item, dataQuery: item.dataQuery.replace('US_REGION_DB', 'EU_REGION_DB') };
          }
          return item;
        });
      }

      // If a mandatory item is missing, add a placeholder or a default
      if (userContext.department === 'Sales' && !enforcedDashboard.items.some(item => item.componentType === 'SalesChart')) {
        enforcedDashboard.items.unshift({ // Add to the beginning
          id: "mandatory-sales-chart",
          width: "full",
          componentType: "SalesChart",
          dataQuery: "SELECT total_sales FROM sales_global WHERE period='current_month'",
          aiConfig: { model: "ComplianceEngine", generatedAt: new Date().toISOString(), relevanceScore: 1.0 },
          layoutPriority: 20,
          contextualTags: ['mandatory', 'sales']
        });
        issues.push("Enforced: Added mandatory 'SalesChart' for Sales department.");
      }


      enforcedDashboard.generationMetadata = {
        ...enforcedDashboard.generationMetadata,
        optimizationScore: Math.max(0, (enforcedDashboard.generationMetadata?.optimizationScore || 0) - 0.1), // Penalize for enforcement
        fallbackUsed: enforcedDashboard.generationMetadata?.fallbackUsed || false,
        aiModelUsed: enforcedDashboard.generationMetadata?.aiModelUsed || 'Gemini-Pro-v1.5 (Enforced)',
        timestamp: new Date().toISOString(),
      };

      telemetryService.logEvent("ComplianceEnforcementComplete", { userId: userContext.userId, finalIssues: issues, compliantItemsCount: enforcedDashboard.items.length });
      return enforcedDashboard;
    }
    return dashboard;
  }
}

